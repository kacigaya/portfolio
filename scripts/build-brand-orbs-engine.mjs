// Turbopack has no built-in `?raw` import, and the authored BrandOrbs component
// expects the orb engine as a string. Rather than add a loader dependency, the
// same extraction the authored component did at runtime happens here at author
// time and lands in a generated module. brand-orbs.test.ts re-runs this against
// the checked-in source so the two can never drift.
//
// Usage: bun scripts/build-brand-orbs-engine.mjs
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const SOURCE_PATH = join(root, "components/effects/brand-orbs/sources/brand-orbs-v2.html");
export const ENGINE_PATH = join(root, "components/effects/brand-orbs/sources/engine.generated.ts");

// The revision this port was verified against; the skill pins it.
export const SOURCE_SHA256 = "c2733de8cf7ba5fa4723297b600e9a0ad6949779fb0ab0734c9a95fb26443314";

// Verbatim from the authored BrandOrbs.tsx: the orb engine is the last <script>
// in the specimen document; earlier ones only drive the catalog page chrome.
export function extractOrbEngine(source) {
  const scripts = [...source.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/gi)];
  return scripts.at(-1)?.[1] ?? "";
}

export function buildEngineModule() {
  const source = readFileSync(SOURCE_PATH, "utf8");
  const digest = createHash("sha256").update(source).digest("hex");
  if (digest !== SOURCE_SHA256) {
    throw new Error(`brand-orbs-v2.html is ${digest}, expected the verified ${SOURCE_SHA256}`);
  }
  const engine = extractOrbEngine(source);
  if (!engine) throw new Error("no <script> found in brand-orbs-v2.html");
  return [
    "// Generated by scripts/build-brand-orbs-engine.mjs — do not edit.",
    "// Source: sources/brand-orbs-v2.html @ " + SOURCE_SHA256.slice(0, 12),
    "export const BRAND_ORBS_ENGINE = " + JSON.stringify(engine) + ";",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(ENGINE_PATH, buildEngineModule());
  console.log(`wrote ${ENGINE_PATH}`);
}
